-- ---------------------------------------------------------------- Rechte
-- Row Level Security auf allen Tabellen. app: nur eingeloggte, aktive Nutzer. legacy: niemand über die API.
revoke all on schema app from anon, public;
grant usage on schema app to authenticated, service_role;
grant all on all tables in schema app to authenticated, service_role;
grant usage, select on all sequences in schema app to authenticated, service_role;
revoke all on all tables in schema app from anon;
alter default privileges in schema app grant all on tables to authenticated, service_role;
alter default privileges in schema app grant usage, select on sequences to authenticated, service_role;
revoke execute on all functions in schema app from public, anon;
grant execute on all functions in schema app to authenticated, service_role;

revoke all on schema legacy from anon, authenticated, public;

do $$
declare t record;
begin
  for t in select schemaname, tablename from pg_tables where schemaname in ('app','legacy') loop
    execute format('alter table %I.%I enable row level security', t.schemaname, t.tablename);
  end loop;
  for t in select tablename from pg_tables where schemaname = 'app' and tablename <> 'profile' loop
    execute format('drop policy if exists eingeloggt_alles on app.%I', t.tablename);
    execute format('create policy eingeloggt_alles on app.%I for all to authenticated using ((select app.ist_aktiv())) with check ((select app.ist_aktiv()))', t.tablename);
  end loop;
end $$;

-- Profile: jeder aktive Nutzer liest, nur Admin ändert.
drop policy if exists profile_lesen on app.profile;
create policy profile_lesen on app.profile for select to authenticated using (id = (select auth.uid()) or (select app.ist_admin()));
drop policy if exists profile_admin on app.profile;
create policy profile_admin on app.profile for all to authenticated using ((select app.ist_admin())) with check ((select app.ist_admin()));

