-- Grundschema Knoblau-App. Wiederholbar ausführbar (idempotent).
-- legacy = Rohdaten 1:1 (kein API-Zugriff), app = sauberes Arbeitsschema.

create schema if not exists legacy;
create schema if not exists app;

-- ---------------------------------------------------------------- Nutzer
create table if not exists app.profile (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text,
  rolle text not null default 'nutzer' check (rolle in ('admin','nutzer')),
  aktiv boolean not null default true,
  erstellt_am timestamptz not null default now()
);

create or replace function app.ist_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from app.profile p where p.id = (select auth.uid()) and p.rolle = 'admin' and p.aktiv)
$$;

create or replace function app.ist_aktiv() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from app.profile p where p.id = (select auth.uid()) and p.aktiv)
$$;

